"""Can the phone's AR poses fix the learned models' scale? ETH3D, poses degraded to AR-like error.

    uv run python -m evals.pose_priors prepare    # AR-like poses per group -> eth3d/<scene>/ar_poses/
    make pose-priors-models                       # MapAnything with and without those poses
    uv run python -m evals.pose_priors score      # -> results/pose_priors.md

Two ways to use the poses, at each pose setting in `evals.ar_poses`:
- (a) MapAnything given the poses and the intrinsics as priors, one joint run per group. Run at
  392 px on the long side, 2 and 4 views: its native 518 px, or 8 views, needs more than the
  roughly 4 GB one process may use on this shared machine. The same runs without poses are the
  baseline, so the comparison holds resolution and precision fixed.
- (b) MoGe-2 per-photo metric depth, each photo rescaled to the points triangulated from features
  matched across the group with those poses (`evals.triangulate`), then placed with the same poses
  and fused.
As a control, MoGe-2 depth placed with the same poses but not rescaled shows what the rescale adds.
Everything is scored on the fixed evaluation sets of `evals.recon`.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import cv2
import numpy as np

from evals.ar_poses import SETTINGS, group_poses
from evals.eth3d import SCENES, read_views
from evals.paths import ETH3D_DIR
from evals.recon import (
    COHORTS,
    HEADER,
    PREDICTIONS,
    RANGES,
    WIDTH,
    Method,
    Scene,
    load_prediction,
    model_frame_method,
    score_groups,
    table,
)
from evals.triangulate import view_scales

GROUP_SIZES = ("2", "4", "8")  # triangulation needs at least two photos
MODEL = "moge2"


def pose_file(scene: str, setting: str):
    return ETH3D_DIR / scene / "ar_poses" / f"{setting}.json"


def prepare(scene: str) -> None:
    views = {v.name: v for v in read_views(ETH3D_DIR / scene)}
    groups = json.loads((ETH3D_DIR / scene / "subsets.json").read_text())
    groups = {n: g for n, g in groups.items() if n in GROUP_SIZES}
    for setting in SETTINGS:
        path = pose_file(scene, setting)
        path.parent.mkdir(exist_ok=True)
        path.write_text(json.dumps(group_poses(views, groups, setting)))
    count = sum(map(len, groups.values()))
    print(f"{scene}: AR-like poses for {count} groups x {len(SETTINGS)} settings")


def pose_methods(scene: Scene) -> dict[str, Method]:
    root = PREDICTIONS / scene.name
    gray = {}

    def image(name):
        if name not in gray:
            gray[name] = cv2.imread(str(scene.dir / f"images_{WIDTH}" / f"{name}.jpg"), 0)
        return gray[name]

    def depth_and_K(name):
        d, K, _ = load_prediction(root / MODEL / f"{name}.npz")
        return d, K

    def fused_with(setting, rescale):
        poses_by_group = json.loads(pose_file(scene.name, setting).read_text())

        def method(gid, members):
            if gid not in poses_by_group:
                return None
            T = {m: np.array(poses_by_group[gid]["poses"][m]) for m in members}
            scale = {m: 1.0 for m in members}
            if rescale:
                fits = view_scales(
                    {m: image(m) for m in members},
                    {m: depth_and_K(m)[1] for m in members},
                    T,
                    {m: depth_and_K(m)[0] for m in members},
                    max_reproj_px=SETTINGS[setting].reprojection_px,
                )
                scale = {m: fits[m].scale for m in members}

            def pv(name):
                d, K = depth_and_K(name)
                s = scale[name]
                return (d * s if s is not None else np.full_like(d, np.nan)), K, T[name], True

            return pv

        return method

    methods: dict[str, Method] = {
        "mapanything@392, images only": model_frame_method(root / "ma392_images")
    }
    for setting in SETTINGS:
        methods[f"mapanything@392 + {setting} poses"] = model_frame_method(
            root / f"ma392_{setting}"
        )
    for setting in SETTINGS:
        methods[f"MoGe-2 placed with {setting} poses"] = fused_with(setting, rescale=False)
        methods[f"MoGe-2 rescaled by triangulation, {setting} poses"] = fused_with(
            setting, rescale=True
        )
    return methods


def markdown(results: dict) -> str:
    lines = ["# Pose priors (generated by `uv run python -m evals.pose_priors score`)", "", HEADER]
    lines.append(
        "\nPose settings (assumptions, see `evals/ar_poses.py`): exact = the true poses; "
        "advio_2018 = scale 0.88 to 0.96 per group, 5 cm and 0.2 degrees of noise, from the ADVIO "
        "measurements; modern_assumed = 2% short, 1 cm, 0.1 degrees, a guess with no data."
    )
    for scene, ranges in results.items():
        for range_name in RANGES:
            rows = [(m, n, r) for m, per_n in ranges[range_name].items() for n, r in per_n.items()]
            for cohort in COHORTS:
                lines += ["", f"## {scene}, {range_name}, {cohort}", ""]
                lines += table(rows, cohort)
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("step", choices=["prepare", "score"])
    args = ap.parse_args()
    if args.step == "prepare":
        for s in SCENES:
            prepare(s)
        return
    results = {}
    for s in SCENES:
        scene = Scene(s)
        results[s] = score_groups(scene, pose_methods(scene), sizes=(2, 4, 8))
    out = Path(__file__).resolve().parents[1] / "results"
    (out / "pose_priors.json").write_text(json.dumps(results, indent=1))
    md = markdown(results)
    (out / "pose_priors.md").write_text(md)
    print(md)


if __name__ == "__main__":
    main()
